// Reads CHANGELOG.md, extracts the latest documented release with the
// shared parser in utils/changelog.js, and writes constants/changelogMeta.js
// for the app to import. The app cannot read Markdown at runtime (Metro has
// no raw-file import and we add no transformer), so this generated module is
// the bridge between the changelog and the Settings → About screen.
//
// Usage: node --import ./scripts/register.mjs ./scripts/generate-changelog-meta.mjs
// Optional argv overrides (used by scripts/verify-changelog-parse.mjs to test
// against fixtures without touching the real files):
//   … generate-changelog-meta.mjs [changelogPath] [outputPath]
//
// The script never fails the build: a missing or version-less changelog
// produces null metadata plus a warning, keeping `npm start` healthy.

import { isAbsolute, resolve } from 'node:path';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { latestDocumentedRelease, parseChangelogSections } from '../utils/changelog';

const repoRoot = fileURLToPath(new URL('../', import.meta.url));
const fromArg = (arg, fallback) =>
  arg ? (isAbsolute(arg) ? arg : resolve(repoRoot, arg)) : resolve(repoRoot, fallback);

const changelogPath = fromArg(process.argv[2], 'CHANGELOG.md');
const outputPath = fromArg(process.argv[3], 'constants/changelogMeta.js');

let release = null;
let sections = [];
let warning = null;
try {
  const text = readFileSync(changelogPath, 'utf8');
  release = latestDocumentedRelease(text);
  sections = parseChangelogSections(text);
  if (!release) warning = 'no versioned release heading found ([Unreleased] alone does not count)';
} catch (error) {
  warning = `could not read ${changelogPath} (${error.code ?? error.message})`;
}

const meta = {
  latestVersion: release?.version ?? null,
  releaseDate: release?.date ?? null,
};

const banner = [
  '// Generated by scripts/generate-changelog-meta.mjs — do not edit by hand.',
  '// Source: CHANGELOG.md parsed by utils/changelog.js at the moment of',
  '// generation (`npm run gen:changelog`, also run by the prestart/preweb/',
  '// preandroid hooks). Committed so Metro, web exports, and EAS builds',
  '// always resolve it. changelogMeta = latest release for the About row;',
  '// changelogSections = the full newest-first history for /changelog.',
].join('\n');

const body = [
  `export const changelogMeta = ${JSON.stringify(meta, null, 2)};`,
  '',
  `export const changelogSections = ${JSON.stringify(sections, null, 2)};`,
  '',
].join('\n');

writeFileSync(outputPath, `${banner}\n${body}`);

if (warning) {
  console.warn(`[gen:changelog] wrote null metadata: ${warning}`);
} else {
  console.log(
    `[gen:changelog] latest documented release: ${meta.latestVersion}` +
      (meta.releaseDate ? ` (${meta.releaseDate})` : ' (undated)'),
  );
}
